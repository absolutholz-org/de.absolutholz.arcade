export const PUZZLE_CATALOG: NonogramPuzzle[] = RAW_PUZZLES.map((raw) => {
	const { rowClues, colClues } = computeClues(raw.grid, raw.width, raw.height);
	return {
		...raw,
		rowClues,
		colClues,
	};
});

export const PUZZLES_BY_DIFFICULTY: Record<DifficultyId, NonogramPuzzle[]> = {
	easy: PUZZLE_CATALOG.filter((p) => p.difficulty === 'easy'),
	medium: PUZZLE_CATALOG.filter((p) => p.difficulty === 'medium'),
	hard: PUZZLE_CATALOG.filter((p) => p.difficulty === 'hard'),
};

export function getPuzzleById(id: string): NonogramPuzzle | undefined {
	return PUZZLE_CATALOG.find((p) => p.id === id);
}

export function getDefaultPuzzle(difficulty: DifficultyId = 'easy'): NonogramPuzzle {
	const group = PUZZLES_BY_DIFFICULTY[difficulty];
	return group[0] ?? PUZZLE_CATALOG[0];
}
