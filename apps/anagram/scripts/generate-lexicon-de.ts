function isValidGermanWord(word: string): boolean {
	const tiles = Array.from(word);
	if (tiles.length < 3 || tiles.length > 8) return false;
	if (!VALID_WORD_PATTERN.test(word)) return false;
	if (!VOWEL_PATTERN.test(word)) return false;
	if (TRIPLE_REPEAT_PATTERN.test(word)) return false;
	if (EXCLUDED_NOISE.has(word)) return false;
	return true;
}

export function buildSignatureIndex(words: readonly string[]): Map<string, string[]> {
	const index = new Map<string, string[]>();
	for (const word of words) {
		const signature = Array.from(word).sort().join('');
		const bucket = index.get(signature) ?? [];
		if (!bucket.includes(word)) bucket.push(word);
		index.set(signature, bucket);
	}
	return index;
}

function main() {
	const inputPath = process.argv[2];
	const wordSet = new Set<string>();

	for (const word of CURATED_GERMAN_WORDS) {
		const normalized = word.toLocaleLowerCase('de');
		if (isValidGermanWord(normalized)) {
			wordSet.add(normalized);
		}
	}

	if (inputPath && fs.existsSync(inputPath)) {
		const raw = fs.readFileSync(inputPath, 'utf8');
		const lines = raw.split(/\r?\n/);
		const limit = Math.min(lines.length, 30000);
		for (let i = 0; i < limit; i++) {
			const [token] = lines[i].trim().split(/\s+/);
			if (!token) continue;
			const normalized = token.toLocaleLowerCase('de');
			if (isValidGermanWord(normalized)) {
				wordSet.add(normalized);
			}
		}
	}

	const sortedWords = [...wordSet].sort((a, b) => a.localeCompare(b, 'de'));
	const sigIndex = buildSignatureIndex(sortedWords);

	fs.writeFileSync(OUTPUT_PATH, `${JSON.stringify({ words: sortedWords })}\n`, 'utf8');
	console.log(`Wrote ${sortedWords.length} German words (${sigIndex.size} unique signatures) to ${OUTPUT_PATH}`);
}

main();
