const VALID_PT_WORD_PATTERN = /^[a-záàâãéêíóôõúç]{3,8}$/;

function expandNounOrAdjective(word: string): string[] {
	const forms = [word];
	if (word.endsWith('a') || word.endsWith('e') || word.endsWith('o') || word.endsWith('u') || word.endsWith('i')) {
		forms.push(`${word}s`);
	} else if (word.endsWith('r') || word.endsWith('z')) {
		forms.push(`${word}es`);
	} else if (word.endsWith('m')) {
		forms.push(`${word.slice(0, -1)}ns`);
	} else if (word.endsWith('al')) {
		forms.push(`${word.slice(0, -2)}ais`);
	} else if (word.endsWith('el')) {
		forms.push(`${word.slice(0, -2)}éis`);
	} else if (word.endsWith('ol')) {
		forms.push(`${word.slice(0, -2)}óis`);
	} else if (word.endsWith('ul')) {
		forms.push(`${word.slice(0, -2)}uis`);
	}
	if (word.endsWith('o') && word.length >= 4) {
		const fem = `${word.slice(0, -1)}a`;
		forms.push(fem, `${fem}s`);
	}
	return forms;
}

function expandVerb(verb: string): string[] {
	const clean = verb.trim().toLowerCase();
	if (clean.length < 4) return [clean];
	const stem = clean.slice(0, -2);
	const ending = clean.slice(-2);

	if (ending === 'ar') {
		return [
			clean,
			`${stem}o`,
			`${stem}a`,
			`${stem}as`,
			`${stem}am`,
			`${stem}ou`,
			`${stem}ava`,
			`${stem}ado`,
			`${stem}ada`,
		];
	}
	if (ending === 'er') {
		return [
			clean,
			`${stem}o`,
			`${stem}e`,
			`${stem}es`,
			`${stem}em`,
			`${stem}eu`,
			`${stem}ia`,
			`${stem}ido`,
			`${stem}ida`,
		];
	}
	if (ending === 'ir') {
		return [
			clean,
			`${stem}o`,
			`${stem}e`,
			`${stem}es`,
			`${stem}em`,
			`${stem}iu`,
			`${stem}ia`,
			`${stem}ido`,
			`${stem}ida`,
		];
	}
	return [clean];
}

function buildPortugueseLexicon() {
	// Map from normalized unaccented spelling -> canonical display word (preferring accented forms)
	const byNormalizedWord = new Map<string, string>();

	const addCandidate = (raw: string, preferOverwrite: boolean) => {
		const word = raw.trim().toLowerCase();
		const charLen = Array.from(word).length;
		if (charLen < 3 || charLen > 8) return;
		if (!VALID_PT_WORD_PATTERN.test(word)) return;
		const norm = normalizeWord(word);
		if (norm.length < 3 || norm.length > 8 || !/^[a-z]{3,8}$/.test(norm)) return;

		const existing = byNormalizedWord.get(norm);
		if (!existing) {
			byNormalizedWord.set(norm, word);
			return;
		}
		const isAccented = word !== norm;
		const existingAccented = existing !== norm;
		if (preferOverwrite || (isAccented && !existingAccented)) {
			byNormalizedWord.set(norm, word);
		}
	};

	// 1. Add base words and their noun/adjective inflections
	for (const raw of BASE_WORDS) {
		for (const inflected of expandNounOrAdjective(raw.trim().toLowerCase())) {
			addCandidate(inflected, false);
		}
	}

	// 2. Add regular verb conjugations
	for (const verb of REGULAR_VERBS) {
		for (const conjugated of expandVerb(verb)) {
			addCandidate(conjugated, false);
		}
	}

	// 3. Add accented words last with priority so accented display forms always win
	for (const accented of ACCENTED_WORDS) {
		addCandidate(accented, true);
	}

	const words = [...byNormalizedWord.values()].sort((a, b) => a.localeCompare(b, 'pt'));
	const normalizedMap = new Map<string, string[]>();

	for (const word of words) {
		const sig = signatureOf(word);
		const bucket = normalizedMap.get(sig) ?? [];
		if (!bucket.includes(word)) {
			bucket.push(word);
		}
		normalizedMap.set(sig, bucket);
	}

	const sortedSignatures = [...normalizedMap.keys()].sort();
	const normalized: Record<string, string[]> = {};
	for (const sig of sortedSignatures) {
		const bucket = normalizedMap.get(sig);
		if (bucket) {
			normalized[sig] = bucket;
		}
	}

	return { words, normalized };
}

